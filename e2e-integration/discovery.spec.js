import { test, expect } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'

for (const viewport of [{ width: 1280, height: 850 }, { width: 390, height: 844 }]) {
  test(`approved popup preserves reading, keyboard and new-tab behavior at ${viewport.width}px`, async ({ page, context }, testInfo) => {
    await page.setViewportSize(viewport)
    await page.goto('/topic/building-chronology')
    const trigger = page.locator('a.keyword-connection').filter({ hasText: /^observation$/i }).first()
    await trigger.scrollIntoViewIfNeeded()
    await trigger.focus()
    const position = await page.evaluate(() => scrollY)
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog')
    await expect(dialog).toBeVisible()
    await expect(dialog.getByRole('link', { name: /Open Full Topic/ })).toBeVisible()
    expect(await page.evaluate(() => scrollY)).toBe(position)
    await expect(dialog.getByRole('button', { name: 'Close topic preview' })).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(dialog.getByRole('link', { name: /Open Full Topic/ })).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(dialog.getByRole('button', { name: 'Close topic preview' })).toBeFocused()
    const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(scan.violations.map(v => v.id)).toEqual([])
    await page.screenshot({path: testInfo.outputPath('topic-popup.png')})
    const newTab = context.waitForEvent('page')
    await dialog.getByRole('link', { name: /Open Full Topic/ }).click()
    const full = await newTab
    await expect(full).toHaveURL(/\/topic\/reading-evidence$/)
    await full.close()
    expect(await page.evaluate(() => scrollY)).toBe(position)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await trigger.click()
    await page.getByRole('button', { name: 'Close topic preview' }).click()
    await expect(dialog).toHaveCount(0)
    expect(await page.evaluate(() => scrollY)).toBe(position)
  })
}

test('tag discovery and subject practice use current published canonical content', async ({ page }) => {
  await page.goto('/topic/reading-evidence')
  await page.getByRole('link', { name: 'Synthetic reading toolkit' }).click()
  await expect(page).toHaveURL(/\/tags\/synthetic-reading-toolkit$/)
  await expect(page.getByText('2 published articles')).toBeVisible()
  await expect(page.locator('.search-result')).toHaveCount(2)
  const scan = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(scan.violations.map(v => v.id)).toEqual([])
  await page.goto('/tags/unknown-tag')
  await expect(page.getByRole('heading', { name: 'This tag is not available.' })).toBeVisible()
  await page.goto('/practice/historical-thinking')
  await expect(page.getByText('40 questions', { exact: true })).toBeVisible()
  expect(await page.locator('fieldset').count()).toBe(40)
  await page.getByRole('radio').first().check()
  await page.getByRole('button', { name: 'Check my answers →' }).click()
  await expect(page.getByRole('heading', { name: 'Understand your answers.' })).toBeVisible()
  await expect(page.locator('.answer-review')).toHaveCount(40)
  await expect(page.getByText('These results are held only in this page. No learner attempt has been saved.')).toBeVisible()
})

test('Admin Suggest Connections preserves proposals and allows explicit reject/approve', async ({ page }) => {
  const credentials = readFileSync(join(process.env.PREPAL_DEMO_ROOT, 'admin-credentials.txt'), 'utf8')
  const admin = 'http://127.0.0.1:8001'
  await page.goto(`${admin}/admin/login/?next=/admin/`)
  await page.locator('[name=username]').fill(credentials.match(/^Username: (.+)$/m)[1])
  await page.locator('[name=password]').fill(credentials.match(/^Password: (.+)$/m)[1])
  await page.locator('input[type=submit]').click()
  await page.goto(`${admin}/admin/content/topic/?q=Reading+the+past`)
  await page.locator('#result_list input.action-select').first().check()
  await page.locator('select[name=action]').first().selectOption('suggest_connections')
  await page.getByRole('button', { name: 'Run', exact: true }).first().click()
  await expect(page.locator('.messagelist')).toContainText('connection proposals')
  await page.goto(`${admin}/admin/content/keywordlinkproposal/?q=chronology`)
  const row = page.locator('#result_list tbody tr').filter({hasText: 'Reading the past, one source at a time'}).first()
  await row.locator('input.action-select').check()
  await page.locator('select[name=action]').first().selectOption('reject_connections')
  await page.getByRole('button', {name:'Run',exact:true}).first().click()
  await expect(page.locator('.messagelist')).toContainText('Connection rejected')
  await row.locator('input.action-select').check()
  await page.locator('select[name=action]').first().selectOption('approve_connections')
  await page.getByRole('button', {name:'Run',exact:true}).first().click()
  await expect(page.locator('.messagelist')).toContainText('Connection approved')
})
