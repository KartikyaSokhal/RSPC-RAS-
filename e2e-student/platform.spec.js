async function signup(page, name) {
  await page.goto('/')
  await page.getByRole('banner').getByRole('link',{name:'Sign Up'}).click()
  await expect(page.getByRole('button',{name:'Continue with Google'})).toBeDisabled()
  await page.getByLabel('Full name').fill(name)
  await page.getByLabel('Username *').fill(name)
  await page.getByLabel('Email *').fill(name+'@example.test')
  await page.getByLabel('Password *').fill('Synthetic-Learning-423!')
  await page.getByRole('button',{name:'Create Account & Start Learning →'}).click()
  await expect(page).toHaveURL(/dashboard$/)
  await expect(page.getByRole('heading',{name:'Welcome back, '+name})).toBeVisible()
}

