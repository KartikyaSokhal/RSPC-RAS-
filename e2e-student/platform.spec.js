for(const width of [320,768]) {
  test(`student navbar supports keyboard, themes and wrapping at ${width}px`,async({page})=>{
    await page.setViewportSize({width,height:900})
    await page.emulateMedia({reducedMotion:'reduce'})
    await signup(page,'nav-'+width+'-'+Date.now())
    for(const theme of ['light','dark']) {
      if(await page.locator('html').getAttribute('data-theme')!==theme) await page.getByRole('button',{name:`Switch to ${theme} theme`}).click()
      await page.locator('.account-menu summary').focus()
      await page.keyboard.press('Enter')
      await expect(page.getByRole('button',{name:'Logout',exact:true})).toBeVisible()
      await page.keyboard.press('Tab')
      await expect(page.getByRole('button',{name:'Logout',exact:true})).toBeFocused()
      await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
      const scan=await new AxeBuilder({page}).include('.site-header').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze()
      expect(scan.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>({target:n.target,summary:n.failureSummary}))}))).toEqual([])
      await page.locator('.account-menu summary').focus()
      await page.keyboard.press('Enter')
    }
  })
}

